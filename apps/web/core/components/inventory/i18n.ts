const DICTIONARIES: Record<InventoryLocale, Dictionary> = { en, es, pl };

export function inventoryLocale(plane: string | undefined): InventoryLocale {
  const base = (plane ?? "").slice(0, 2);
  return base === "es" || base === "pl" ? base : "en";
}

export function inventoryT(
  locale: InventoryLocale,
  key: InventoryKey,
  params?: Readonly<Record<string, string | number>>
): string {
  const text = DICTIONARIES[locale][key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole));
}

export type InventoryT = (key: InventoryKey, params?: Readonly<Record<string, string | number>>) => string;

export function makeInventoryT(planeLocale: string | undefined): InventoryT {
  const locale = inventoryLocale(planeLocale);
  return (key, params) => inventoryT(locale, key, params);
}

/** Every dictionary has every key (the type says so; this is for the unit test). */
export const INVENTORY_DICTIONARIES: Readonly<Record<InventoryLocale, Readonly<Dictionary>>> = DICTIONARIES;

/** Navigation keys whose label comes from here instead of Plane's dictionaries. */
export const INVENTORY_NAV_LABELS: Readonly<Record<string, InventoryKey>> = {
  inventory: "nav_inventory",
  features_inventory: "feature_title",
  shopping_list: "widget_title",
};

/** The label of a navigation entry: the fork's own for inventory, Plane's `t` for the rest. */
export function navLabel(key: string, i18nKey: string, t: (key: string) => string, planeLocale: string): string {
  // Own keys only: a plain object would answer "constructor" from its prototype (phase 5 audit).
  const own = Object.hasOwn(INVENTORY_NAV_LABELS, key) ? INVENTORY_NAV_LABELS[key] : undefined;
  return own ? inventoryT(inventoryLocale(planeLocale), own) : t(i18nKey);
}
